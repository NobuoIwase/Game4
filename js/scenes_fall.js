/* 帯の締めを一行選ぶ。★同じ場面の中では揺れないよう、相手の id で決め打ちする */
function fallCoda(heroId, kind, monId){
  if(kind!=='pin' && kind!=='capture' && kind!=='climax' && kind!=='charmbind') return null;
  const T=FALL_CODA[heroId]||FALL_CODA.lumina;
  const band=(typeof fallTier==='function')?fallTier(heroId):'resist';
  const arr=T[band]||T.resist; if(!arr||!arr.length) return null;
  let h=0; const s=(monId||'default')+'|'+kind;
  for(let i=0;i<s.length;i++) h=(h*31+s.charCodeAt(i))|0;
  return arr[Math.abs(h)%arr.length];
}
