/* 図鑑の段階: -1=未知 / 0=見かけた / 1=追記一 / 2=追記二 / 3=追記三 */
function codexStage(id){
  const c=(META.codex||{})[id];
  const owned=META.cards[id]&&META.cards[id].owned;
  if(!c && !owned) return -1;
  if(!c) return 0;
  if(c.capture>0 || c.climax>=3) return 3;
  if(c.climax>0 || c.met>=10) return 2;
  if(c.met>0) return 1;
  return 0;
}
const escC=s=>String(s).replace(/[&<>"]/g,ch=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[ch]));
/* 手記の記法をHTMLへ: ~~取り消し~~ / {{乱れ}} / ※欄外 */
function noteHtml(txt){
  return txt.split('\n').map(line=>{
    let l=escC(line);
    l=l.replace(/~~(.+?)~~/g,'<s>$1</s>').replace(/\{\{(.+?)\}\}/g,'<span class="shaky">$1</span>');
    if(line.startsWith('※')) return '<div class="margin">'+l+'</div>';
    return '<div>'+l+'</div>';
  }).join('');
}

