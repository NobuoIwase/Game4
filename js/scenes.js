'use strict';
/* ============================================================
   scenes.js — シーンテキストの受け口(フック)
   ------------------------------------------------------------
   本ファイルはシステム側の「差し込み口」のみを定義する。
   本文テキストはここには書かず、別途の執筆パイプラインが
   このスキーマに沿ってデータを追加する。

   スキーマ(1エントリ = 1シーン):
     SCENES.capture[<monsterId>] = {
       title: '見出し',
       beats: ['拍1', '拍2', ...],   // 順に表示される本文ブロック
     };
   ・capture: 捕獲確定時。ключ=とどめ/拘束主のモンスターid。
     'default' はフォールバック。
   ・エントリが無い場合、システムは機構的なリザルト表示のみ行う。
   ・表示側(ui.js)は beats を連結してスクロールボックスに流すだけで、
     内容には関知しない。
============================================================ */
const SCENES={
  capture:{
    // default: { title:'…', beats:['…'] },
  },
};
function sceneFor(kind,id){
  const t=SCENES[kind]||{};
  return t[id]||t.default||null;
}
