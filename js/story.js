/* v2.1 ADV行の正規化: 文字列でも {s,t,f} でも受け、{s,t,f} に揃える。文字列は「」で始まればルミナの台詞、（）は独白、それ以外は地の文 */
function storyNorm(lines){
  const out=[]; if(!lines) return out;
  for(const l of lines){
    if(l==null) continue;
    if(typeof l==='string'){ const t=l.trim(); if(!t) continue;
      const m=t.match(/^「(.*)」$/s); if(m){ out.push({s:'lumina',t:m[1]}); continue; }
      const m2=t.match(/^（(.*)）$/s); if(m2){ out.push({s:'lumina',t:m2[1]}); continue; }
      out.push({s:'n',t}); continue; }
    if(typeof l==='object' && typeof l.t==='string' && l.t.trim()){ out.push({s:l.s||'n', t:l.t.trim(), f:l.f}); }
  }
  return out;
}
/* 物語画面・結果画面向けの整形(話者名付き) */
function storyLineHtml(l){
  const x=storyNorm([l])[0]; if(!x) return '';
  const e=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  if(x.s==='lumina') return `<div class="sl"><b class="who">ルミナ</b>「${e(x.t)}」</div>`;
  if(x.s==='town') return `<div class="sl"><b class="who t">街の人</b>「${e(x.t)}」</div>`;
  if(x.s==='voice') return `<div class="sl"><b class="who v">声</b>「${e(x.t)}」</div>`;
  return `<div class="sn">${e(x.t)}</div>`;
}
/* retry: 変奏の配列(v2.1: 配列の配列)か、「§」区切りの1本の配列(旧形式)。1つを選んで返す */
function storyRetry(){
  if(STORY.retry.length && Array.isArray(STORY.retry[0])) return STORY.retry[(Math.random()*STORY.retry.length)|0]||[];
  const groups=[]; let cur=[];
  for(const l of STORY.retry){ if(l.startsWith('§')){ if(cur.length) groups.push(cur); cur=[]; const rest=l.slice(1).trim(); if(rest) cur.push(rest); } else cur.push(l); }
  if(cur.length) groups.push(cur);
  return groups.length?groups[(Math.random()*groups.length)|0]:[];
}
